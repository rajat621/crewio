import fs from 'fs';
import fsp from 'fs/promises';
import os from 'os';
import path from 'path';
import { randomUUID } from 'crypto';
import {
  PutObjectCommand,
  GetObjectCommand,
  DeleteObjectCommand,
  HeadObjectCommand,
} from '@aws-sdk/client-s3';
import { getSignedUrl as presignUrl } from '@aws-sdk/s3-request-presigner';
import env from '../config/env.js';
import getR2Client from '../config/r2.client.js';

/**
 * ============================================================================
 * storage.service.js — single storage abstraction for the whole backend.
 * ============================================================================
 *
 * Nothing outside this file should call `fs.readFileSync`, `fs.existsSync`,
 * `fs.createReadStream`, etc. on an *uploaded/generated asset* (timesheets,
 * invoices, templates, signatures, stamps, logos). Business logic (invoice
 * generation, AI extraction, downloads, ...) only ever talks to the methods
 * exported from here, and never needs to know or care whether
 * STORAGE_DRIVER is "local" or "r2".
 *
 * Concepts:
 *  - "key": the tenant-scoped relative key, e.g. companies/{id}/{folder}/{file}.
 *    For the local driver this is exactly the same string used as the web
 *    path (with a leading slash stripped). For r2 it's the literal S3 object
 *    key. FileRecord.storageKey / FileRecord.path both resolve to this.
 *  - "driver": 'local' | 'r2'. Every method accepts an explicit driver so
 *    per-record drivers (old local records alongside new r2 records) keep
 *    working after a cutover; if omitted it falls back to STORAGE_DRIVER.
 */

const storageRoot = path.resolve(process.cwd(), 'src', 'storage');
const tempRoot = path.join(os.tmpdir(), 'crewcontrol-storage-tmp');

const isR2 = () => env.storage.driver === 'r2';
const resolveDriver = (driver) => driver || (isR2() ? 'r2' : 'local');

/**
 * Every object key is scoped under the owning company (or owner, for the
 * rare record with no company yet). This is what actually prevents one
 * tenant from ever being able to reach another tenant's files - the app
 * never trusts a client-supplied path, only the companyId/ownerId taken
 * from the authenticated request.
 *
 *   companies/{companyId}/{folder}/{filename}
 *   owners/{ownerId}/{folder}/{filename}          (no company yet)
 */
export const buildTenantKey = ({ companyId, ownerId, folder, filename }) => {
  const safeFolder = String(folder || 'misc').replace(/[^a-zA-Z0-9_-]/g, '');
  const safeFilename = String(filename || 'file').replace(/[^a-zA-Z0-9._-]/g, '_');
  const scope = companyId ? `companies/${companyId}` : `owners/${ownerId}`;
  return `${scope}/${safeFolder}/${safeFilename}`;
};

// A "key" and a local web-path ("/companies/...") refer to the same object;
// normalize away the leading slash so both forms work everywhere below.
const normalizeKey = (keyOrWebPath) => String(keyOrWebPath || '').replace(/^\/+/, '');

// D19.8 finding (defense-in-depth, not currently exploitable): every
// caller of this function today passes a key that was either generated by
// buildTenantKey() above (which strips `/` and any `..`-forming character
// from both the folder and filename segments before they're ever joined)
// or read back from a FileRecord document written that way - confirmed via
// repository-wide search of every objectExists/getObjectBuffer/
// downloadToTempFile/streamObject caller. But nothing in this function
// itself enforces that invariant; a future caller passing an unsanitized
// key (a `../../../etc/passwd`-style value) would resolve to a real path
// outside storageRoot with no defense at this layer. path.join() happily
// resolves `..` segments, so a plain prefix concatenation isn't enough -
// this checks the final resolved path is still actually inside
// storageRoot and throws otherwise, same trust-nothing-twice principle as
// the rest of this file's write path.
const keyToLocalAbsolutePath = (key) => {
  const resolved = path.resolve(storageRoot, normalizeKey(key));
  const rootWithSep = storageRoot.endsWith(path.sep) ? storageRoot : `${storageRoot}${path.sep}`;
  if (resolved !== storageRoot && !resolved.startsWith(rootWithSep)) {
    throw new Error('Resolved storage path escapes storageRoot');
  }
  return resolved;
};

/**
 * Infer the driver a previously-stored path/key was written with, for the
 * (common, expected) case where the caller only has the plain string that
 * was persisted on a document and not a FileRecord with an explicit
 * storageDriver field. Local paths always start with '/', r2 keys never do.
 * Always prefer an explicit driver (e.g. FileRecord.storageDriver) over this
 * when one is available.
 */
export const driverFromStoredPath = (storedPath) => {
  const value = String(storedPath || '');
  if (!value) return resolveDriver();
  return value.startsWith('/') ? 'local' : 'r2';
};

const ensureLocalDir = async (dirPath) => {
  await fsp.mkdir(dirPath, { recursive: true });
};

const streamToBuffer = async (stream) => {
  const chunks = [];
  for await (const chunk of stream) {
    chunks.push(Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk));
  }
  return Buffer.concat(chunks);
};

// ---------------------------------------------------------------------------
// Write
// ---------------------------------------------------------------------------

/**
 * Save a buffer (e.g. from multer memoryStorage) under a tenant-scoped key.
 * Returns { driver, key, path } where `path` is what gets stored on the
 * FileRecord/Invoice document - a local web path for 'local', the R2 key
 * for 'r2'.
 */
export const saveBuffer = async ({ companyId, ownerId, folder, filename, buffer, mimetype }) => {
  const key = buildTenantKey({ companyId, ownerId, folder, filename });

  if (isR2()) {
    const client = getR2Client();
    await client.send(
      new PutObjectCommand({
        Bucket: env.storage.r2.bucket,
        Key: key,
        Body: buffer,
        ContentType: mimetype || 'application/octet-stream',
      })
    );
    return { driver: 'r2', key, path: key };
  }

  // local fallback - identical behavior to the original disk storage
  const absPath = keyToLocalAbsolutePath(key);
  await ensureLocalDir(path.dirname(absPath));
  await fsp.writeFile(absPath, buffer);
  return { driver: 'local', key, path: `/${key}` };
};

/**
 * Persist a file that some other library already wrote to a *local working
 * path* (pdf-lib / pdfkit both need a real filesystem path to write to).
 * This always routes through saveBuffer, so both drivers behave identically
 * no matter where the source file physically lives (storageRoot, an OS temp
 * dir, whatever) - there's no more special-casing based on path location.
 * The caller owns cleanup of `absolutePath` (see cleanupTempFile).
 */
export const saveLocalFile = async ({ absolutePath, companyId, ownerId, folder, filename }) => {
  const finalFilename = filename || path.basename(absolutePath);
  const buffer = await fsp.readFile(absolutePath);
  const mimetype = finalFilename.toLowerCase().endsWith('.pdf')
    ? 'application/pdf'
    : 'application/octet-stream';
  return saveBuffer({ companyId, ownerId, folder, filename: finalFilename, buffer, mimetype });
};


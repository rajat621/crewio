export const objectExists = async ({ key, driver } = {}) => {
  const d = resolveDriver(driver);
  const k = normalizeKey(key);
  if (!k) return false;

  if (d === 'r2') {
    try {
      const client = getR2Client();
      await client.send(new HeadObjectCommand({ Bucket: env.storage.r2.bucket, Key: k }));
      return true;
    } catch {
      return false;
    }
  }

  return fs.existsSync(keyToLocalAbsolutePath(k));
};

export const getObjectBuffer = async ({ key, driver } = {}) => {
  const d = resolveDriver(driver);
  const k = normalizeKey(key);

  if (d === 'r2') {
    const client = getR2Client();
    const result = await client.send(new GetObjectCommand({ Bucket: env.storage.r2.bucket, Key: k }));
    return streamToBuffer(result.Body);
  }

  return fsp.readFile(keyToLocalAbsolutePath(k));
};

/**
 * Some libraries (pdf-lib, pdfplumber/OCR via the AI microservice, etc.)
 * need a real filesystem path, not a buffer. This gets the object onto
 * local disk when needed and hands back a path plus a cleanup() you MUST
 * call when done.
 *
 * For the local driver this is a zero-copy no-op: it just resolves the
 * already-existing absolute path, and cleanup() does nothing - local mode
 * behaves exactly as it always did.
 */
export const downloadToTempFile = async ({ key, driver, filename } = {}) => {
  const d = resolveDriver(driver);
  const k = normalizeKey(key);

  if (d === 'local') {
    const absolutePath = keyToLocalAbsolutePath(k);
    return { path: absolutePath, isTemp: false, cleanup: async () => {} };
  }

  const buffer = await getObjectBuffer({ key: k, driver: 'r2' });
  await ensureLocalDir(tempRoot);
  const safeName = String(filename || path.basename(k) || 'file').replace(/[^a-zA-Z0-9._-]/g, '_');
  const tempPath = path.join(tempRoot, `${randomUUID()}-${safeName}`);
  await fsp.writeFile(tempPath, buffer);
  return { path: tempPath, isTemp: true, cleanup: async () => cleanupTempFile(tempPath) };
};

/**
 * Same idea as downloadToTempFile but hands back an isolated, disposable
 * temp *directory* containing the file - useful for pipelines that write
 * sibling artifacts (OCR debug images, extracted pages, etc.) next to the
 * source file. Works uniformly for both drivers (local mode gets a real
 * copy in an isolated dir too, so callers never have to special-case it).
 */
export const downloadToTempDirectory = async ({ key, driver, filename } = {}) => {
  const d = resolveDriver(driver);
  const k = normalizeKey(key);
  await ensureLocalDir(tempRoot);
  const dir = await fsp.mkdtemp(path.join(tempRoot, 'dir-'));
  const safeName = String(filename || path.basename(k) || 'file').replace(/[^a-zA-Z0-9._-]/g, '_');
  const destPath = path.join(dir, safeName);

  if (d === 'local') {
    await fsp.copyFile(keyToLocalAbsolutePath(k), destPath);
  } else {
    const buffer = await getObjectBuffer({ key: k, driver: 'r2' });
    await fsp.writeFile(destPath, buffer);
  }

  return { dir, path: destPath, cleanup: async () => cleanupTempDirectory(dir) };
};

/**
 * A time-limited, access-controlled download URL. R2 only - callers on the
 * local driver should use streamObject() instead. Access control must
 * already have been checked by the caller (see files.controller.js) before
 * a URL is handed back; this call doesn't know or care who's asking.
 */
export const getSignedUrl = async ({ key, driver, expiresIn } = {}) => {
  const d = resolveDriver(driver);
  if (d !== 'r2') {
    throw new Error('getSignedUrl() is only supported for the r2 driver');
  }
  const client = getR2Client();
  const command = new GetObjectCommand({ Bucket: env.storage.r2.bucket, Key: normalizeKey(key) });
  return presignUrl(client, command, {
    expiresIn: expiresIn || env.storage.r2.signedUrlExpirySeconds,
  });
};

/**
 * Stream an object straight into an Express response. Used by download
 * endpoints so they never need to touch fs / R2 clients directly.
 */
export const streamObject = async ({ key, driver, res, contentType, disposition } = {}) => {
  const d = resolveDriver(driver);
  const k = normalizeKey(key);

  if (contentType) res.setHeader('Content-Type', contentType);
  if (disposition) res.setHeader('Content-Disposition', disposition);

  if (d === 'r2') {
    const client = getR2Client();
    const result = await client.send(new GetObjectCommand({ Bucket: env.storage.r2.bucket, Key: k }));
    await new Promise((resolve, reject) => {
      result.Body.on('error', reject);
      res.on('finish', resolve);
      res.on('error', reject);
      result.Body.pipe(res);
    });
    return;
  }

  const absolutePath = keyToLocalAbsolutePath(k);
  await new Promise((resolve, reject) => {
    const stream = fs.createReadStream(absolutePath);
    stream.on('error', reject);
    res.on('finish', resolve);
    res.on('error', reject);
    stream.pipe(res);
  });
};

/**
 * Access-controlled retrieval, kept for callers that want a redirect (r2) or
 * a stream-it-yourself path (local) rather than having streamObject() write
 * the response directly. Caller MUST have already verified the requester
 * owns/has-access-to this record - this only decides HOW to fetch the
 * bytes, not WHO can ask.
 */
export const getAccessUrlOrPath = async ({ key, driver } = {}) => {
  const d = resolveDriver(driver);
  if (d === 'r2') {
    const url = await getSignedUrl({ key, driver: 'r2' });
    return { type: 'redirect', url };
  }
  return { type: 'stream', absolutePath: keyToLocalAbsolutePath(normalizeKey(key)) };
};

// ---------------------------------------------------------------------------
// Delete / cleanup
// ---------------------------------------------------------------------------

export const deleteObject = async ({ key, driver } = {}) => {
  const d = resolveDriver(driver);
  const k = normalizeKey(key);

  if (d === 'r2') {
    const client = getR2Client();
    await client.send(new DeleteObjectCommand({ Bucket: env.storage.r2.bucket, Key: k }));
    return;
  }

  const absPath = keyToLocalAbsolutePath(k);
  if (fs.existsSync(absPath)) await fsp.unlink(absPath);
};

/** Safe to call on any path (temp or otherwise); never throws. */
export const cleanupTempFile = async (filePath) => {
  if (!filePath) return;
  try {
    await fsp.unlink(filePath);
  } catch (error) {
    if (error?.code !== 'ENOENT') {
      console.error('cleanupTempFile failed:', error.message);
    }
  }
};

/** Safe to call on any directory; never throws. */
export const cleanupTempDirectory = async (dirPath) => {
  if (!dirPath) return;
  try {
    await fsp.rm(dirPath, { recursive: true, force: true });
  } catch (error) {
    console.error('cleanupTempDirectory failed:', error.message);
  }
};

/**
 * Reserve a fresh path inside the shared temp root for a working file this
 * process is about to create (e.g. a freshly rendered invoice PDF), without
 * downloading anything. Caller writes to it, then typically calls
 * saveLocalFile() to persist the result and cleanupTempFile() to remove the
 * working copy - this keeps generated output out of the permanent local
 * storage tree entirely, so nothing generated is ever left behind on disk
 * for either driver.
 */
export const reserveTempFilePath = async (filename) => {
  await ensureLocalDir(tempRoot);
  const safeName = String(filename || 'file').replace(/[^a-zA-Z0-9._-]/g, '_');
  return path.join(tempRoot, `${randomUUID()}-${safeName}`);
};

export default {
  buildTenantKey,
  driverFromStoredPath,
  saveBuffer,
  saveLocalFile,
  objectExists,
  getObjectBuffer,
  downloadToTempFile,
  downloadToTempDirectory,
  getSignedUrl,
  streamObject,
  getAccessUrlOrPath,
  deleteObject,
  cleanupTempFile,
  cleanupTempDirectory,
  reserveTempFilePath,
};
